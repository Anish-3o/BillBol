import { useMemo } from 'react';
import { Link } from 'react-router';
import { useSession } from '../hooks/useAuth';
import { formatPaise } from '../lib/money';
import { qrSvg, upiLink } from '../lib/upi';

type Props = { amountPaise: number; note: string; caption?: string };

// A "scan to pay" QR with the exact amount, for the shop's UPI ID. If the shop has not set a
// UPI ID yet, the owner gets a link to Settings and staff are told to ask the owner.
export function UpiQr({ amountPaise, note, caption = 'Customer scans with any UPI app' }: Props) {
  const { tenant, user } = useSession();
  // The SVG is generated by our own code from the link (no user HTML in it), so it is safe to
  // insert as markup.
  const svg = useMemo(
    () => (tenant.upiId ? qrSvg(upiLink({ upiId: tenant.upiId, payeeName: tenant.name, amountPaise, note }), 168) : null),
    [tenant.upiId, tenant.name, amountPaise, note],
  );

  if (!svg) {
    return (
      <div className="upi-missing">
        {user.role === 'owner' ? (
          <>
            Add your shop's UPI ID in <Link to="/settings">Settings</Link> to show a "scan to pay" QR with the exact amount.
          </>
        ) : (
          <>Ask the owner to add the shop's UPI ID in Settings to show a "scan to pay" QR.</>
        )}
      </div>
    );
  }
  return (
    <div className="upi-qr">
      <span className="upi-code" dangerouslySetInnerHTML={{ __html: svg }} role="img" aria-label={`UPI QR code for ${formatPaise(amountPaise)}`} />
      <div className="upi-text">
        <strong>{formatPaise(amountPaise)}</strong>
        <span>{caption}</span>
        <small>{tenant.upiId}</small>
      </div>
    </div>
  );
}
